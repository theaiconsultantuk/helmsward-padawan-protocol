// Generates functions/_data.js from the repo data so the Worker needs no filesystem. Run: node cf/build.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const d = (p) => new URL(`../data/${p}`, import.meta.url);
const csv = readFileSync(existsSync(d("amazon-gifts.csv")) ? d("amazon-gifts.csv") : d("gifts.csv"), "utf8");
const watch = existsSync(d("tmdb-starwars.json")) ? JSON.parse(readFileSync(d("tmdb-starwars.json"), "utf8")) : [];
writeFileSync(new URL("./functions/_data.js", import.meta.url), `// GENERATED by cf/build.mjs. Do not edit.\nexport const GIFTS_CSV = ${JSON.stringify(csv)};\nexport const WATCH = ${JSON.stringify(watch)};\n`);
console.log("wrote functions/_data.js", csv.length, "bytes csv,", watch.length, "watch items");
