// Bundle the Meterless World Model reference (TypeScript) into one ESM file the service can import.
// Usage: node scripts/build_world_model.mjs [outfile]   (default src/engines/world-model/index.mjs)
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outfile = path.resolve(root, process.argv[2] ?? "src/engines/world-model/index.mjs");

await build({
  absWorkingDir: root,
  entryPoints: ["engines/world-model/reference/src/index.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  minify: false,
  outfile,
  banner: {
    js: "// GENERATED by scripts/build_world_model.mjs from engines/world-model/reference/src (Meterless World Model, Apache-2.0, commit 1742dec). Do not edit; rebuild.",
  },
});
